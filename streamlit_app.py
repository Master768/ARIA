# Initialize ReportWriter
writer = ReportWriter()
reports_dir = writer.reports_dir

st.title("📊 Orchestra Report Studio")
st.markdown("Review, edit, and sign off on data analysis reports generated by the multi-agent orchestration pipeline.")

# Load manifest data
manifest_data = writer._load_manifest()
reports = manifest_data.get("reports", [])

# Sidebar Panel
st.sidebar.header("📁 Report Archive")
if not reports:
    st.sidebar.info("No reports found in the archive.")
    selected_report_entry = None
else:
    # Build list of options for selectbox
    options = []
    option_map = {}
    for idx, r in enumerate(reports):
        label = f"[{r.get('status')}] {r.get('original_question')[:30]} ({r.get('timestamp')})"
        options.append(label)
        option_map[label] = r
        
    selected_label = st.sidebar.selectbox("Select Report to Review", options)
    selected_report_entry = option_map.get(selected_label)

# Main Review Workspace
if selected_report_entry is None:
    st.info("Select a report from the sidebar to begin review.")
else:
    # Load markdown file content
    md_filename = selected_report_entry.get("md_path")
    md_path = os.path.join(reports_dir, md_filename)
    
    st.subheader(f"Question: {selected_report_entry.get('original_question')}")
    
    # Status Metadata Bar
    status = selected_report_entry.get("status")
    val_status = selected_report_entry.get("validation_status")
    timestamp = selected_report_entry.get("timestamp")
    
    status_class = f"badge-{status.lower()}"
    val_class = "badge-passed" if val_status == "COMPLETE" else "badge-needs-review"
    val_text = "VERIFIED" if val_status == "COMPLETE" else "NEEDS REVIEW / FAILED"
    
    st.markdown(f"""
        <div>
            <span class="status-badge {status_class}">Status: {status}</span>
            <span class="status-badge {val_class}">Critic: {val_text}</span>
            <span style="font-size: 0.9rem; color: #a0aec0;">Generated on: {timestamp}</span>
        </div>
        <br>
    """, unsafe_allow_html=True)
    
    if not os.path.exists(md_path):
        st.error(f"Markdown report file not found at: `{md_path}`")
    else:
        # Read file contents
        with open(md_path, "r", encoding="utf-8") as f:
            md_content = f.read()
            
        if status == "DRAFT":
            # Editable Text Area for drafts
            edited_content = st.text_area(
                "Edit Report Content (Markdown)",
                value=md_content,
                height=450,
                key=f"editor_{md_filename}"
            )
            
            # Action Buttons
            col1, col2, _ = st.columns([1, 1, 4])
            with col1:
                if st.button("✅ Approve Sign-off", use_container_width=True):
                    # Define approved file names
                    approved_md_filename = md_filename.replace("_DRAFT.md", "_APPROVED.md")
                    approved_md_path = os.path.join(reports_dir, approved_md_filename)
                    approved_docx_filename = md_filename.replace("_DRAFT.md", "_APPROVED.docx")
                    approved_docx_path = os.path.join(reports_dir, approved_docx_filename)
                    
                    # 1. Save edited markdown to the approved file path
                    with open(approved_md_path, "w", encoding="utf-8") as f:
                        f.write(edited_content)
                        
                    # 2. Compile DOCX version
                    writer.convert_to_docx(edited_content, approved_docx_path)
                    
                    # 3. Update status in manifest.json
                    writer.update_manifest_status(
                        draft_filename=md_filename,
                        new_status="APPROVED",
                        new_filename=approved_md_filename,
                        docx_filename=approved_docx_filename
                    )
                    
                    # 4. Delete draft markdown file
                    if os.path.exists(md_path):
                        os.remove(md_path)
                        
                    st.success("Report successfully approved, archived, and compiled to DOCX!")
                    st.balloons()
                    time.sleep(1.0)
                    st.rerun()
                    
            with col2:
                if st.button("❌ Reject", use_container_width=True):
                    # Update status in manifest.json
                    writer.update_manifest_status(
                        draft_filename=md_filename,
                        new_status="REJECTED"
                    )
                    st.warning("Report status set to REJECTED.")
                    time.sleep(1.0)
                    st.rerun()
                    
            st.markdown("### Preview Draft")
            st.markdown(edited_content)
            
        else:
            # Display view-only content for APPROVED/REJECTED reports
            st.markdown("### Report Content")
            st.markdown(md_content)
            
            # If approved, show download options for md and docx
            if status == "APPROVED":
                st.success("This report is signed off and archived.")
                
                # Check for files
                docx_filename = selected_report_entry.get("docx_path")
                docx_path = os.path.join(reports_dir, docx_filename) if docx_filename else ""
                
                col1, col2, _ = st.columns([1, 1, 4])
                with col1:
                    with open(md_path, "r", encoding="utf-8") as f:
                        st.download_button(
                            label="📥 Download Markdown",
                            data=f.read(),
                            file_name=md_filename,
                            mime="text/markdown",
                            use_container_width=True
                        )
                if docx_path and os.path.exists(docx_path):
                    with col2:
                        with open(docx_path, "rb") as f:
                            st.download_button(
                                label="📥 Download DOCX Word File",
                                data=f.read(),
                                file_name=docx_filename,
                                mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                                use_container_width=True
                            )
            elif status == "REJECTED":
                st.error("This report was rejected.")
